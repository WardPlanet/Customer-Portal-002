    /* ---------- Add-block menu (Paragraph / Header / Steps) ---------- */
    var blockMenu = byId('block-menu');
    var menuOpener = null;
    var menuGetInsertBefore = null;
    var menuInserterTypes = null;

    function closeBlockMenu() {
      blockMenu.hidden = true;
    }

    // Places the menu under the button that opened it (or above it when there is no room below)
    function positionBlockMenu() {
      var rect = menuOpener.getBoundingClientRect();
      var menuWidth = blockMenu.offsetWidth;
      var menuHeight = blockMenu.offsetHeight;
      var left = rect.left + rect.width / 2 - menuWidth / 2;
      left = Math.max(8, Math.min(left, window.innerWidth - menuWidth - 8));
      var top = rect.bottom + 8;
      if (top + menuHeight > window.innerHeight - 8) { top = Math.max(8, rect.top - menuHeight - 8); }
      blockMenu.style.left = left + 'px';
      blockMenu.style.top = top + 'px';
    }

    function focusFirstMenuItem() {
      var first = blockMenu.querySelector('.menu-panel:not([hidden]) button:not([hidden])');
      if (first) { first.focus(); }
    }

    // The menu has two panels: the block types ('main') and the header levels ('headers')
    // Levels deeper than the hierarchy allows at the insertion point are greyed out
    function updateHeaderLevelButtons() {
      var beforeNode = menuGetInsertBefore ? menuGetInsertBefore() : null;
      var deepest = deepestAllowedHeaderLevel(beforeNode);
      blockMenu.querySelectorAll('#menu-headers [data-level]').forEach(function (item) {
        var blocked = Number(item.getAttribute('data-level')) > deepest;
        item.setAttribute('aria-disabled', String(blocked));
        item.title = blocked ? 'Headers step down one level at a time. The deepest level allowed here is H' + deepest + '.' : '';
      });
    }

    function showMenuPanel(name) {
      byId('menu-main').hidden = name !== 'main';
      byId('menu-headers').hidden = name !== 'headers';
      if (name === 'headers') { updateHeaderLevelButtons(); }
      positionBlockMenu();
      focusFirstMenuItem();
    }

    // getInsertBefore returns the node the new block goes before (null means the end of the page).
    // allowedTypes limits which options show (null shows all of them).
    function openBlockMenu(opener, getInsertBefore, allowedTypes) {
      if (!blockMenu.hidden && menuOpener === opener) {
        closeBlockMenu();
        return;
      }
      menuOpener = opener;
      menuGetInsertBefore = getInsertBefore;
      menuInserterTypes = allowedTypes || null;
      blockMenu.querySelectorAll('#menu-main button').forEach(function (item) {
        item.hidden = !!allowedTypes && allowedTypes.indexOf(item.getAttribute('data-type')) < 0;
      });
      blockMenu.hidden = false;

      showMenuPanel('main');
    }

    blockMenu.addEventListener('click', function (event) {
      if (event.target.closest('#menu-back')) { showMenuPanel('main'); return; }
      var item = event.target.closest('[data-type]');
      if (!item) { return; }
      if (item.getAttribute('aria-disabled') === 'true') {
        showNotice('Headers step down one level at a time, so that level can\u2019t go here.');
        return;
      }
      if (item.hasAttribute('data-submenu')) { showMenuPanel('headers'); return; }
      var beforeNode = menuGetInsertBefore ? menuGetInsertBefore() : null;
      closeBlockMenu();
      insertBlockAndFocus(item.getAttribute('data-type'), beforeNode, Number(item.getAttribute('data-level')) || undefined, menuInserterTypes);
    });

    blockMenu.addEventListener('keydown', function (event) {
      var items = Array.prototype.slice.call(blockMenu.querySelectorAll('.menu-panel:not([hidden]) button:not([hidden])'));
      var index = items.indexOf(document.activeElement);
      if (event.key === 'ArrowDown') {
        event.preventDefault();
        items[(index + 1) % items.length].focus();
      } else if (event.key === 'ArrowUp') {
        event.preventDefault();
        items[(index - 1 + items.length) % items.length].focus();
      } else if (event.key === 'ArrowRight' && document.activeElement.hasAttribute('data-submenu')) {
        event.preventDefault();
        showMenuPanel('headers');
      } else if (event.key === 'ArrowLeft' && !byId('menu-headers').hidden) {
        event.preventDefault();
        showMenuPanel('main');
      }
    });

    document.addEventListener('keydown', function (event) {
      if (event.key === 'Escape' && !blockMenu.hidden) {
        closeBlockMenu();
        if (menuOpener && document.body.contains(menuOpener)) { menuOpener.focus(); }
      }
    });
    document.addEventListener('click', function (event) {
      var clickedOpener = menuOpener && menuOpener.contains(event.target);
      if (!blockMenu.hidden && !blockMenu.contains(event.target) && !clickedOpener) { closeBlockMenu(); }
    });
