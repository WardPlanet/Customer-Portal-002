    /* ---------- Export: editor state -> plain text ---------- */
    function escapeLine(line) {
      var first = line.charAt(0);
      return (first === '[' || first === ESCAPE) ? ESCAPE + line : line;
    }

    function unescapeLine(line) {
      return line.charAt(0) === ESCAPE ? line.slice(1) : line;
    }

    function serializeDraft() {
      var out = [];

      function section(name, lines) {
        out.push('[' + name + ']');
        lines.forEach(function (line) { out.push(escapeLine(line)); });
        out.push('');
      }

      function textLines(value) { return value ? value.split(NL) : []; }

      out.push('PAGE EDITOR DRAFT');
      out.push('FORMAT: ' + FORMAT_VERSION);
      out.push('SAVED: ' + new Date().toISOString());
      out.push('Open this file with "Open draft" in the page editor to fill in every section.');
      out.push('');

      section('TITLE', textLines(readText(titleEl)));
      section('SUBTITLE', textLines(readText(subtitleEl)));
      section('SUMMARY', textLines(readText(summaryEl)));

      readBlocks().forEach(function (block, index) {
        var prefix = 'BLOCK ' + (index + 1) + ' ';
        if (block.type === 'step') {
          section(prefix + 'STEP NUMBER', [String(block.number)]);
          section(prefix + 'STEP TITLE', textLines(block.title));
          section(prefix + 'STEP TEXT', textLines(block.text));
        } else if (block.type === 'header') {
          section(prefix + 'HEADER ' + block.level, textLines(block.text));
        } else {
          section(prefix + block.type.toUpperCase(), textLines(block.text));
        }
      });

      // Remember how many blocks sit above the "+ Add a block" button so the layout reopens the same way
      var addButton = byId('add-block');
      var aboveButton = contentBlocks().filter(function (block) {
        return block.compareDocumentPosition(addButton) & Node.DOCUMENT_POSITION_FOLLOWING;
      }).length;
      section('ADD BLOCK BUTTON', [String(aboveButton)]);
      section('KEYWORDS', state.keywords);

      section('PAGE TYPE', textLines(state.pageType));
      section('WHERE THIS LIVES', state.locations.filter(function (l) { return l.on; }).map(function (l) { return l.name; }));
      section('LINKED TEAM MEMBERS', state.members);
      section('REVIEWER', textLines(state.reviewer));
      section('VISIBILITY', textLines(state.visibility));

      return out.join(NL);
    }

    function draftFilename() {
      var slug = readText(titleEl).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 60);
      return (slug || 'untitled-page') + '-draft.txt';
    }

    /* ---------- Import: plain text -> editor state ---------- */
    function parseDraft(text) {
      var sections = {};
      var current = null;
      text.replace(/\r\n?/g, NL).split(NL).forEach(function (line) {
        var header = /^\[([A-Z0-9 ]+)\]$/.exec(line);
        if (header) {
          current = header[1];
          sections[current] = [];
        } else if (current !== null) {
          sections[current].push(unescapeLine(line));
        }
      });
      return sections;
    }

    function looksLikeDraft(sections) {
      return Object.keys(sections).some(function (name) {
        return KNOWN_SECTIONS.indexOf(name) >= 0 || /^BLOCK \d+ /.test(name) || /^STEP \d+ (TITLE|TEXT)$/.test(name);
      });
    }

    // Turns the BLOCK n ... sections (or the older STEP n ... sections) into an ordered list of blocks
    function readDraftBlocks(sections, body) {
      var blocks = [];
      var numbers = {};
      Object.keys(sections).forEach(function (name) {
        var match = /^BLOCK (\d+) (PARAGRAPH|HEADER [1-5]|HEADER|NOTE|WARNING|STEP TITLE|STEP TEXT|STEP NUMBER)$/.exec(name);
        if (match) { numbers[Number(match[1])] = true; }
      });

      var ordered = Object.keys(numbers).map(Number).sort(function (a, b) { return a - b; });
      ordered.forEach(function (n) {
        var prefix = 'BLOCK ' + n + ' ';
        var headerLevel = [1, 2, 3, 4, 5].filter(function (level) {
          return sections[prefix + 'HEADER ' + level];
        })[0];
        var textType = ['paragraph', 'header', 'note', 'warning'].filter(function (type) {
          return sections[prefix + type.toUpperCase()];
        })[0];
        if (headerLevel) {
          blocks.push({ type: 'header', level: headerLevel, text: body(prefix + 'HEADER ' + headerLevel) });
        } else if (textType) {
          blocks.push({ type: textType, text: body(prefix + textType.toUpperCase()) });
        } else {
          blocks.push({
            type: 'step',
            number: parseInt(body(prefix + 'STEP NUMBER'), 10),
            title: body(prefix + 'STEP TITLE'),
            text: body(prefix + 'STEP TEXT')
          });
        }
      });

      if (!ordered.length) {
        var legacySteps = {};
        Object.keys(sections).forEach(function (name) {
          var match = /^STEP (\d+) (TITLE|TEXT)$/.exec(name);
          if (match) { legacySteps[Number(match[1])] = true; }
        });
        Object.keys(legacySteps).map(Number).sort(function (a, b) { return a - b; }).forEach(function (n) {
          blocks.push({ type: 'step', title: body('STEP ' + n + ' TITLE'), text: body('STEP ' + n + ' TEXT') });
        });
      }

      // A step starts a new section when it is numbered 1, or when it does not follow another step
      blocks.forEach(function (block, index) {
        if (block.type !== 'step') { return; }
        var previous = blocks[index - 1];
        var followsStep = !!previous && previous.type === 'step';
        block.continues = followsStep && (isNaN(block.number) || block.number > 1);
      });

      return blocks;
    }

    function applyDraft(sections) {
      function body(name) { return sections[name] ? sections[name].join(NL).trim() : ''; }
      function list(name) {
        return sections[name] ? sections[name].map(function (l) { return l.trim(); }).filter(Boolean) : [];
      }

      titleEl.textContent = body('TITLE');
      subtitleEl.textContent = body('SUBTITLE');
      summaryEl.innerHTML = markdownToHtml(body('SUMMARY'));

      var blocks = readDraftBlocks(sections, body);
      var aboveButton = parseInt(body('ADD BLOCK BUTTON'), 10);
      layoutContent(blocks, isNaN(aboveButton) ? blocks.length : aboveButton);
      clearSuggestions();
      resetRichSelection();

      var pageType = body('PAGE TYPE');
      state.pageTypes = BASE_PAGE_TYPES.slice();
      if (pageType && state.pageTypes.indexOf(pageType) < 0) { state.pageTypes.push(pageType); }
      state.pageType = pageType;

      var selected = list('WHERE THIS LIVES');
      state.locations = BASE_LOCATIONS.map(function (name) {
        return { name: name, on: selected.indexOf(name) >= 0 };
      });
      selected.forEach(function (name) {
        if (BASE_LOCATIONS.indexOf(name) < 0) { state.locations.push({ name: name, on: true }); }
      });

      state.members = list('LINKED TEAM MEMBERS');
      var reviewer = body('REVIEWER');
      if (reviewer && state.members.indexOf(reviewer) < 0) { state.members.push(reviewer); }
      state.reviewer = reviewer;

      state.visibility = body('VISIBILITY') === 'Client-Safe' ? 'Client-Safe' : 'Internal-Only';
      state.keywords = list('KEYWORDS').slice(0, 20);

      renderSidebar();
      refreshOutline();
    }

