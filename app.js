    /* ---------- Rich text (paragraph blocks only) ----------
       Formatted text is stored in the draft file as plain text:
         **bold**   _italic_   <u>underline</u>   [label](https://example.com)
         - bullet item     1. numbered item
       A backslash in front of a symbol keeps that symbol literal. */
    var BACKSLASH = String.fromCharCode(92);
    var MARKDOWN_SPECIALS = BACKSLASH + '*_[]<>';
    var TOKEN_OPEN = String.fromCharCode(0xE000);
    var TOKEN_CLOSE = String.fromCharCode(0xE001);

    function escapeHtml(text) {
      return text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
    }

    function escapeMarkdown(text) {
      return text.split(String.fromCharCode(160)).join(' ').split('').map(function (ch) {
        return MARKDOWN_SPECIALS.indexOf(ch) >= 0 ? BACKSLASH + ch : ch;
      }).join('');
    }

    function isListLookalike(line) {
      return /^- /.test(line) || /^[0-9]+[.] /.test(line);
    }

    // One inline node (text, bold, italic, underline, link) -> formatted plain text
    function inlineToMarkdown(node) {
      if (node.nodeType === 3) { return escapeMarkdown(node.nodeValue); }
      if (node.nodeType !== 1) { return ''; }
      if (node.tagName === 'BR') { return NL; }

      var inner = Array.prototype.map.call(node.childNodes, inlineToMarkdown).join('');
      var tag = node.tagName;
      if (tag === 'B' || tag === 'STRONG') { return inner ? '**' + inner + '**' : ''; }
      if (tag === 'I' || tag === 'EM') { return inner ? '_' + inner + '_' : ''; }
      if (tag === 'U') { return inner ? '<u>' + inner + '</u>' : ''; }
      if (tag === 'A' && node.getAttribute('href') && node.textContent) {
        var href = node.getAttribute('href').split(' ').join('%20').split(')').join('%29');
        return '[' + escapeMarkdown(node.textContent) + '](' + href + ')';
      }
      return inner;
    }

    // A paragraph field's HTML -> formatted plain text, one line per line break or list item
    function htmlToMarkdown(root) {
      var lines = [];
      var current = '';

      function flush() {
        lines.push(isListLookalike(current) ? BACKSLASH + current : current);
        current = '';
      }

      function walk(node) {
        if (node.nodeType !== 1) { current += inlineToMarkdown(node); return; }
        var tag = node.tagName;
        if (tag === 'BR') {
          flush();
        } else if (tag === 'UL' || tag === 'OL') {
          if (current !== '') { flush(); }
          Array.prototype.forEach.call(node.children, function (item, index) {
            lines.push((tag === 'UL' ? '- ' : (index + 1) + '. ') + inlineToMarkdown(item).split(NL).join(' '));
          });
        } else if (tag === 'DIV' || tag === 'P') {
          if (current !== '') { flush(); }
          Array.prototype.forEach.call(node.childNodes, walk);
          if (current !== '') { flush(); }
        } else {
          current += inlineToMarkdown(node);
        }
      }

      Array.prototype.forEach.call(root.childNodes, walk);
      if (current !== '') { flush(); }
      return lines.join(NL);
    }

    // One line of formatted plain text -> HTML
    function inlineMarkdownToHtml(text) {
      var stash = [];
      function keep(html) {
        stash.push(html);
        return TOKEN_OPEN + (stash.length - 1) + TOKEN_CLOSE;
      }

      // Escaped symbols stay literal
      var work = '';
      for (var i = 0; i < text.length; i += 1) {
        var following = text.charAt(i + 1);
        if (text.charAt(i) === BACKSLASH && following && MARKDOWN_SPECIALS.indexOf(following) >= 0) {
          work += keep(escapeHtml(following));
          i += 1;
        } else {
          work += text.charAt(i);
        }
      }

      work = escapeHtml(work);
      work = work.replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, function (match, label, url) {
        if (!/^(https?:[/][/]|mailto:)/i.test(url)) { return match; }
        return keep('<a href="' + url + '">' + label + '</a>');
      });
      work = work.replace(/\*\*(.+?)\*\*/g, '<b>$1</b>');
      work = work.replace(/_(.+?)_/g, '<i>$1</i>');
      work = work.replace(/&lt;u&gt;(.+?)&lt;[/]u&gt;/g, '<u>$1</u>');

      var tokenPattern = new RegExp(TOKEN_OPEN + '([0-9]+)' + TOKEN_CLOSE, 'g');
      for (var pass = 0; pass < 3; pass += 1) {
        work = work.replace(tokenPattern, function (match, index) { return stash[Number(index)]; });
      }
      return work;
    }

    // Formatted plain text -> a paragraph field's HTML
    function markdownToHtml(markdown) {
      if (!markdown) { return ''; }
      var html = '';
      var openList = '';
      var needsBreak = false;

      markdown.split(NL).forEach(function (line) {
        var bullet = /^- (.*)$/.exec(line);
        var numbered = /^[0-9]+[.] (.*)$/.exec(line);
        var listTag = bullet ? 'ul' : (numbered ? 'ol' : '');

        if (openList && openList !== listTag) {
          html += '</' + openList + '>';
          openList = '';
        }
        if (listTag) {
          if (!openList) {
            html += '<' + listTag + '>';
            openList = listTag;
          }
          html += '<li>' + inlineMarkdownToHtml((bullet || numbered)[1]) + '</li>';
          needsBreak = false;
          return;
        }

        var text = line;
        var rest = line.slice(1);
        if (line.charAt(0) === BACKSLASH && isListLookalike(rest)) { text = rest; }
        if (needsBreak) { html += '<br>'; }
        html += inlineMarkdownToHtml(text);
        needsBreak = true;
      });

      if (openList) { html += '</' + openList + '>'; }
      return html;
    }

