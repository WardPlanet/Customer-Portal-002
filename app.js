    function createInserter(allowedTypes) {
      var line = document.createElement('div');
      line.className = 'section-insert';

      var button = document.createElement('button');
      button.type = 'button';
      button.className = 'section-insert-btn';
      button.setAttribute('aria-label', 'Add a block here');
      button.title = 'Add a block here';
      button.innerHTML = PLUS_ICON;
      button.addEventListener('click', function () {
        // New blocks go directly below this line, each with its own insert line below it
        openBlockMenu(button, function () { return line.nextSibling; }, allowedTypes);
      });

      line.appendChild(button);
      return line;
    }

    /* ---------- Page layout: blocks, insert lines and the "+ Add a block" button ---------- */
    // The row under each step section. "Add step" adds another step to the section (no insert
    // line in between); "+ Warning" and "+ Note" add that callout directly below the section.
    function createStepActions() {
      var row = document.createElement('div');
      row.className = 'step-actions';

      function addAction(label, className, iconHtml, onClick) {
        var button = document.createElement('button');
        button.type = 'button';
        button.className = className;
        // A plus, then the block's symbol (Warning and Note), then the label
        var plus = document.createElement('span');
        plus.textContent = '+';
        var text = document.createElement('span');
        text.textContent = label;
        button.appendChild(plus);
        if (iconHtml) { button.insertAdjacentHTML('beforeend', iconHtml); }
        button.appendChild(text);
        button.addEventListener('click', onClick);
        row.appendChild(button);
      }

      addAction('Add step', 'step-add', '', function () {
        var block = addBlock('step', {}, row, false);
        markDirty();
        block.querySelector('.step-title').focus();
      });
      addAction('Warning', 'step-warning', WARNING_ICON, function () { addCalloutBelow(row, 'warning'); });
      addAction('Note', 'step-note', NOTE_ICON, function () { addCalloutBelow(row, 'note'); });
      return row;
    }

    function addCalloutBelow(row, type) {
      var block = addBlock(type, {}, row.nextSibling, null);
      markDirty();
      block.querySelector('[contenteditable]').focus();
    }

    function createAddBlockButton() {
      var button = document.createElement('button');
      button.type = 'button';
      button.className = 'add-block';
      button.id = 'add-block';
      button.textContent = '+ Add a block';
      button.addEventListener('click', function () {
        // Full menu; the new block goes directly below this button
        openBlockMenu(button, function () { return button.nextSibling; }, null);
      });
      return button;
    }

    // Insert lines sit below the opening paragraph and below every block that is added later.
    // There are none directly above or below "+ Add a block"; the button covers that spot.
    // The title and description are single fields, so they get no insert line.
    // aboveButton is how many blocks sit above the "+ Add a block" button.
    function layoutContent(blocks, aboveButton) {
      var count = Math.max(0, Math.min(aboveButton, blocks.length));
      contentEl.textContent = '';
      contentEl.appendChild(createInserter(null));

      function appendAddButton() {
        contentEl.appendChild(createAddBlockButton());
      }

      if (count === 0) { appendAddButton(); }
      blocks.forEach(function (values, index) {
        var isLastAboveButton = index === count - 1;
        var next = blocks[index + 1];
        // Steps in the same section sit together, and a Note or Warning that follows a step section
        // belongs to it, so neither gets an insert line in between
        var skipsInserter = !isLastAboveButton && values.type === 'step' && next
          && ((next.type === 'step' && next.continues) || next.type === 'note' || next.type === 'warning');

        contentEl.appendChild(buildBlockElement(values.type, values));
        // The last block above the button needs no insert line: "+ Add a block" sits right below it
        if (!skipsInserter && !isLastAboveButton) {
          contentEl.appendChild(createInserter(null));
        }
        if (isLastAboveButton) { appendAddButton(); }
      });

      refreshBlocks();
    }

    /* ---------- Required fields ---------- */
    function clearBlockError(block) {
      block.classList.remove('has-error');
      var message = block.querySelector('.field-error');
      if (message) { message.remove(); }
    }

    function flagBlock(block, message, container) {
      block.classList.add('has-error');
      var note = document.createElement('p');
      note.className = 'field-error';
      note.setAttribute('role', 'alert');
      note.textContent = message;
      (container || block).appendChild(note);
    }

    var REQUIRED_FIELDS = [
      { el: titleEl, label: 'page title', message: 'Add a page title to save a draft.' },
      { el: subtitleEl, label: 'description', message: 'Add a description to save a draft.' },
      { el: summaryEl, label: 'opening paragraph', message: 'Add an opening paragraph to save a draft.' }
    ];

    function anyStepHasTitle() {
      return stepBlocks().some(function (block) {
        return readText(block.querySelector('.step-title')) !== '';
      });
    }

    function isDraftComplete() {
      var fieldsFilled = REQUIRED_FIELDS.every(function (field) { return readText(field.el) !== ''; });
      return fieldsFilled && anyStepHasTitle();
    }

    // Grey out Save draft and Submit until every required field is filled in
    function updateSaveState() {
      var complete = isDraftComplete();
      ['save-draft', 'submit-draft'].forEach(function (id) {
        var button = byId(id);
        button.setAttribute('aria-disabled', String(!complete));
        button.title = complete ? '' : 'Fill in the required fields (*) first';
      });

      // AI assist unlocks under the same rule: every required field is filled in
      var aiAssist = byId('ai-assist');
      aiAssist.setAttribute('aria-disabled', String(!complete || aiUnavailable));
      if (aiUnavailable) { aiAssist.title = 'AI assist isn\u2019t available in this view'; }
      else { aiAssist.title = complete ? 'Scan this page and suggest improvements' : 'Fill in the required fields (*) first'; }
    }

    // Returns the list of missing required items (empty when the draft can be saved)
    function validateRequired() {
      document.querySelectorAll('.has-error').forEach(function (block) { clearBlockError(block); });
      var missing = [];

      REQUIRED_FIELDS.forEach(function (field) {
        if (readText(field.el) === '') {
          flagBlock(field.el.closest('.text-block'), field.message);
          missing.push({ label: field.label, target: field.el });
        }
      });

      var steps = stepBlocks();
      if (!steps.length) {
        addStep('', '');
        steps = stepBlocks();
      }
      var hasStepTitle = steps.some(function (block) {
        return readText(block.querySelector('.step-title')) !== '';
      });
      if (!hasStepTitle) {
        var firstTitle = steps[0].querySelector('.step-title');
        flagBlock(steps[0], 'Add at least one step with a title to save a draft.', firstTitle.parentNode);
        missing.push({ label: 'at least one step', target: firstTitle });
      }

      return missing;
    }

    // Adds a block (before beforeNode, or at the end when null) and puts the cursor in it
    function insertBlockAndFocus(type, beforeNode, level, inserterTypes) {
      var block = addBlock(type, { level: level }, beforeNode, inserterTypes);
      markDirty();
      block.querySelector('[contenteditable]').focus();
    }

    /* ---------- On this page (outline) ---------- */
    function refreshOutline() {
      var title = readText(titleEl);
      var outlineTitle = byId('outline-title');
      outlineTitle.textContent = title || 'Untitled page';
      outlineTitle.classList.toggle('is-empty', !title);

      var steps = readSteps();
      var list = byId('outline-list');
      list.textContent = '';
      var allText = [title, readText(subtitleEl), readText(summaryEl)];
      var warningCount = 0;
      readBlocks().forEach(function (block) {
        var item = document.createElement('li');
        if (block.type === 'step') {
          item.textContent = block.number + '. ' + (block.title || 'Untitled step');
          allText.push(block.title, block.text);
        } else if (block.type === 'header') {
          item.textContent = block.text || 'Untitled header';
          item.className = 'outline-header';
          item.style.marginLeft = ((block.level || 2) - 1) * 8 + 'px';
          allText.push(block.text);
        } else {
          allText.push(block.text);
          if (block.type === 'warning') { warningCount += 1; }
          return;
        }
        list.appendChild(item);
      });

      if (warningCount) {
        var warningItem = document.createElement('li');
        warningItem.innerHTML = WARNING_ICON;
        warningItem.appendChild(document.createTextNode(warningCount + (warningCount === 1 ? ' warning' : ' warnings')));
        list.appendChild(warningItem);
      }
      var wordCount = allText.join(' ').split(/\s+/).filter(Boolean).length;
      var minutes = Math.max(1, Math.round(wordCount / 200));

      byId('outline-meta').textContent = steps.length
        ? '~' + minutes + ' min read \u00b7 ' + steps.length + (steps.length === 1 ? ' step' : ' steps')
        : 'No steps yet';

      updateSaveState();
      ensureSectionAiButtons();
    }

    /* ---------- Page Setup: page type ---------- */
