    /* ---------- AI assist: scan the page and suggest changes ---------- */
    var AI_MAX_SUGGESTIONS = 8;
    var aiButton = byId('ai-assist');
    var aiController = null;     // set while a scan runs, so a second click can cancel it
    var aiUnavailable = false;   // set when this view cannot use Claude at all

    function getSample() {
      if (!window.claude || typeof window.claude.use !== 'function') { return Promise.resolve(null); }
      return window.claude.use('sample').catch(function () { return null; });
    }

    // The whole page as plain text, with each section labelled so a suggestion can point at it
    function describePageForAi() {
      var lines = [
        'Page type: ' + (state.pageType || 'not chosen'),
        'Visibility: ' + state.visibility,
        '',
        '[title] ' + readText(titleEl),
        '[description] ' + readText(subtitleEl),
        '[summary] ' + readText(summaryEl)
      ];
      readBlocks().forEach(function (block, index) {
        var label = 'block ' + (index + 1) + ', ' + block.type;
        if (block.type === 'step') {
          lines.push('[' + label + ', numbered ' + block.number + '] title: ' + block.title + ' | text: ' + block.text);
        } else if (block.type === 'header') {
          lines.push('[' + label + ', level ' + block.level + '] ' + block.text);
        } else {
          lines.push('[' + label + '] ' + block.text);
        }
      });
      return lines.join(NL);
    }

    function buildAiPrompt() {
      return [
        'You are an editor reviewing a draft process-documentation page. Read it and suggest improvements.',
        '',
        'Rules:',
        '- Suggest at most ' + AI_MAX_SUGGESTIONS + ' changes, and only ones that clearly help a reader follow the process: unclear or ambiguous wording, missing detail, typos and tone. Only rewrite what is already on the page; never add new sections.',
        '- Do not invent facts, numbers, names, systems or policies that are not on the page. If a rewrite would need a fact only the author knows, keep the original wording for that part instead of guessing.',
        '- If Visibility is Client-Safe, also flag wording that only makes sense for internal staff.',
        '- Keep the author\u2019s voice and keep edits short.',
        '',
        'Reply with ONLY a JSON array (no other text). Each item is an object:',
        '{"target": "title" | "description" | "summary" | "block N", "title": "...", "text": "...", "reason": "..."}',
        '- target: which section the suggestion belongs to. N is the block number shown below.',
        '- "text" is the full replacement for that section\u2019s text. For a step block you may also give a replacement "title". Leave out anything you would not change.',
        '- title and description are single plain-text lines. A summary or paragraph may use **bold**, _italic_, lines starting with "- " for bullets and "1. " for numbers.',
        '- reason: under 120 characters, why the change helps.',
        '- If nothing needs changing, reply with [].',
        '',
        'The page:',
        describePageForAi()
      ].join(NL);
    }

    function oneLine(value, limit) {
      return typeof value === 'string' ? value.split(NL).join(' ').trim().slice(0, limit) : '';
    }

    // Checks one item from the reply; returns a clean suggestion or null
    function cleanSuggestion(item) {
      if (!item || typeof item !== 'object') { return null; }
      var target = String(item.target || '').toLowerCase().trim();
      var isPageField = target === 'title' || target === 'description' || target === 'summary';
      if (!isPageField && !/^block [0-9]+$/.test(target)) { return null; }

      if (item.action === 'add') { return null; }   // suggestions only replace text that is already there
      var text = typeof item.text === 'string' ? item.text.trim().slice(0, 2000) : '';
      var title = oneLine(item.title, 200);
      if (isPageField && !text) { text = title; title = ''; }
      if (!text && !title) { return null; }
      if (target === 'title' || target === 'description') { text = oneLine(text, 300); }

      return {
        target: target,
        title: title,
        text: text,
        reason: oneLine(item.reason, 160)
      };
    }

    function suggestionHost(target, blocks) {
      if (target === 'title') { return titleEl.closest('.text-block'); }
      if (target === 'description') { return subtitleEl.closest('.text-block'); }
      if (target === 'summary') { return summaryEl.closest('.text-block'); }
      return blocks[Number(target.split(' ')[1]) - 1] || null;
    }

    // An edit that would leave the section exactly as it is is not worth showing
    function changesNothing(suggestion, host) {
      if (host.classList.contains('step-block')) {
        var sameTitle = !suggestion.title || suggestion.title === readText(host.querySelector('.step-title'));
        var sameText = !suggestion.text || suggestion.text === readText(host.querySelector('.step-text'));
        return sameTitle && sameText;
      }
      return suggestion.text === readText(host.querySelector('[contenteditable]'));
    }

    function setFieldText(field, text) {
      if (field.hasAttribute('data-rich')) {
        field.innerHTML = markdownToHtml(text);
      } else {
        field.textContent = field.hasAttribute('data-single-line') ? text.split(NL).join(' ') : text;
      }
    }

    // Accepting a suggestion (+) replaces the section's existing text with the suggested text
    function applySuggestion(suggestion, host) {
      if (host.classList.contains('step-block')) {
        if (suggestion.title) { setFieldText(host.querySelector('.step-title'), suggestion.title); }
        if (suggestion.text) { setFieldText(host.querySelector('.step-text'), suggestion.text); }
      } else {
        setFieldText(host.querySelector('[contenteditable]'), suggestion.text);
      }
      markDirty();
      refreshOutline();
    }

    // The small card shown next to a section: the proposal, a + to accept it and an x to dismiss it
    function buildSuggestionPanel(suggestion, host) {
      var panel = document.createElement('div');
      panel.className = 'ai-suggestion';
      panel.setAttribute('role', 'group');
      panel.setAttribute('aria-label', 'AI suggestion');

      var body = document.createElement('div');
      body.className = 'ai-suggestion-body';

      var label = document.createElement('div');
      label.className = 'ai-suggestion-label';
      label.textContent = 'Suggested replacement';
      body.appendChild(label);

      if (suggestion.reason) {
        var reason = document.createElement('p');
        reason.className = 'ai-suggestion-reason';
        reason.textContent = suggestion.reason;
        body.appendChild(reason);
      }

      var preview = document.createElement('div');
      preview.className = 'ai-suggestion-text';
      var isRichPreview = !!host.querySelector('[data-rich]');
      if (isRichPreview) {
        preview.innerHTML = markdownToHtml(suggestion.text);
      } else {
        preview.textContent = [suggestion.title, suggestion.text].filter(Boolean).join(NL);
      }
      body.appendChild(preview);

      var actions = document.createElement('div');
      actions.className = 'ai-suggestion-actions';

      var accept = document.createElement('button');
      accept.type = 'button';
      accept.className = 'ai-accept';
      accept.setAttribute('aria-label', 'Replace the existing text with this suggestion');
      accept.title = 'Replace the existing text with this suggestion';
      accept.innerHTML = PLUS_ICON;
      accept.addEventListener('click', function () {
        applySuggestion(suggestion, host);
        panel.remove();
      });

      var dismiss = document.createElement('button');
      dismiss.type = 'button';
      dismiss.className = 'ai-dismiss';
      dismiss.setAttribute('aria-label', 'Dismiss this suggestion');
      dismiss.title = 'Dismiss this suggestion';
      dismiss.innerHTML = CLOSE_ICON;
      dismiss.addEventListener('click', function () { panel.remove(); });

      actions.appendChild(accept);
      actions.appendChild(dismiss);
      panel.appendChild(body);
      panel.appendChild(actions);
      return panel;
    }

    function clearSuggestions() {
      document.querySelectorAll('.ai-suggestion').forEach(function (panel) { panel.remove(); });
    }

    // Shows one suggestion card inside its section, replacing any card that section already has
    function attachSuggestion(suggestion, host) {
      // Steps lay their content out in a row, so the card goes inside the step's text column
      var container = host.classList.contains('step-block') ? host.querySelector(':scope > div') : host;
      container.querySelectorAll(':scope > .ai-suggestion').forEach(function (panel) { panel.remove(); });
      container.appendChild(buildSuggestionPanel(suggestion, host));
    }

    // Puts each suggestion next to its section; returns how many were shown
    function showSuggestions(result) {
      var list = Array.isArray(result) ? result.slice(0, AI_MAX_SUGGESTIONS) : [];
      var blocks = contentBlocks();
      var shown = 0;

      list.forEach(function (item) {
        var suggestion = cleanSuggestion(item);
        var host = suggestion ? suggestionHost(suggestion.target, blocks) : null;
        if (!host || changesNothing(suggestion, host)) { return; }

        attachSuggestion(suggestion, host);
        shown += 1;
      });
      return shown;
    }

    function setAiBusy(busy) {
      aiButton.classList.toggle('is-busy', busy);
      aiButton.querySelector('.ai-label').textContent = busy ? 'Scanning\u2026 (click to cancel)' : 'AI assist';
    }

    function handleAiError(error) {
      var code = error && error.code;
      if (code === 'cancelled') {
        showNotice('AI scan cancelled.');
      } else if (code === 'not_granted' || code === 'sampling_disabled' || code === 'not_declared' || code === 'capability_disabled' || code === 'capability_removed') {
        aiUnavailable = true;
        updateSaveState();
        showNotice('AI assist isn\u2019t available: this page wasn\u2019t allowed to use Claude.');
      } else if (code === 'rate_limited') {
        showNotice('AI assist has been used a lot just now. Try again in a little while.');
      } else if (code === 'invalid_json' || code === 'empty_completion' || code === 'refused') {
        showNotice('AI assist couldn\u2019t come up with suggestions this time. Try again.');
      } else {
        showNotice('AI assist ran into a problem. Try again.');
      }
    }

    async function runAiAssist() {
      if (aiController) { aiController.abort(); return; }   // a click while scanning cancels
      if (aiUnavailable) {
        showNotice('AI assist isn\u2019t available in this view.');
        return;
      }
      if (!isDraftComplete()) {
        validateRequired();
        showNotice('Fill in the required fields (*) before using AI assist.');
        return;
      }

      aiController = new AbortController();
      var controller = aiController;
      setAiBusy(true);
      try {
        var sample = await getSample();
        if (!sample) {
          aiUnavailable = true;
          updateSaveState();
          showNotice('AI assist isn\u2019t available in this view.');
          return;
        }
        clearSuggestions();
        var result = await sample.json(buildAiPrompt(), { modelTier: 'default', signal: controller.signal });
        var count = showSuggestions(result);
        showNotice(count
          ? 'AI assist has ' + count + (count === 1 ? ' suggestion' : ' suggestions') + '. Use + to replace the existing text or x to dismiss it.'
          : 'AI assist found nothing to change. This page reads well.');
      } catch (error) {
        handleAiError(error);
      } finally {
        aiController = null;
        setAiBusy(false);
      }
    }

    /* ---------- Search keywords: AI writes 10 whenever a draft is saved ----------
       They are stored only in the saved file's [KEYWORDS] section, for the search function.
       They are never shown in the editor or on the page itself. */
    var KEYWORD_COUNT = 10;
    var isMakingKeywords = false;

    function buildKeywordPrompt() {
      return [
        'Write exactly ' + KEYWORD_COUNT + ' search keywords for this process-documentation page. People will type these words into a search box to find the page.',
        '',
        'Rules:',
        '- Use lowercase single words or short two- or three-word phrases.',
        '- Mix the main topic, the tools and systems the page names, the team or role involved, and terms people might search for even if the page does not use those exact words.',
        '- No duplicates, no sentences, and nothing that is not about this page.',
        '',
        'Reply with ONLY a JSON array of ' + KEYWORD_COUNT + ' strings.',
        '',
        'The page:',
        describePageForAi()
      ].join(NL);
    }

    // Tidies the reply: trimmed, lowercase, one line each, no repeats, at most 10
    function cleanKeywords(result) {
      var list = Array.isArray(result) ? result : [];
      var seen = {};
      var keywords = [];
      list.forEach(function (item) {
        var keyword = oneLine(typeof item === 'string' ? item : '', 40).toLowerCase();
        if (keyword && !seen[keyword] && keywords.length < KEYWORD_COUNT) {
          seen[keyword] = true;
          keywords.push(keyword);
        }
      });
      return keywords;
    }

    // Saving never waits on AI forever or fails because of it: without AI the draft saves with the
    // keywords it already had.
    async function refreshKeywords() {
      if (isMakingKeywords || aiUnavailable) { return; }
      isMakingKeywords = true;
      try {
        var sample = await getSample();
        if (!sample) { return; }
        showNotice('Preparing your draft\u2026');
        var keywords = cleanKeywords(await sample.json(buildKeywordPrompt(), { modelTier: 'quick' }));
        if (keywords.length) {
          state.keywords = keywords;
        }
      } catch (error) {
        var code = error && error.code;
        if (code === 'not_granted' || code === 'sampling_disabled' || code === 'not_declared' || code === 'capability_disabled' || code === 'capability_removed') {
          aiUnavailable = true;
          updateSaveState();
        }
      } finally {
        isMakingKeywords = false;
      }
    }

    /* ---------- AI assist for a single section ---------- */
    // Every section that has text gets a small sparkle button in its corner. It asks Claude to
    // improve just that section and shows the answer as a + / x suggestion card.
    var SPARKLE_ICON = '<svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="M12 3l1.8 5.2L19 10l-5.2 1.8L12 17l-1.8-5.2L5 10l5.2-1.8L12 3zM19 15l.8 2.2L22 18l-2.2.8L19 21l-.8-2.2L16 18l2.2-.8L19 15z"/></svg>';

    function allSections() {
      return [titleEl.closest('.text-block'), subtitleEl.closest('.text-block'), summaryEl.closest('.text-block')].concat(contentBlocks());
    }

    function isSectionFilled(host) {
      if (host.classList.contains('step-block')) {
        return readText(host.querySelector('.step-title')) !== '' || readText(host.querySelector('.step-text')) !== '';
      }
      return readText(host.querySelector('[contenteditable]')) !== '';
    }

    // The name used for a section in the prompt: title, description, summary, or "block N"
    function targetNameFor(host) {
      if (host === titleEl.closest('.text-block')) { return 'title'; }
      if (host === subtitleEl.closest('.text-block')) { return 'description'; }
      if (host === summaryEl.closest('.text-block')) { return 'summary'; }
      return 'block ' + (contentBlocks().indexOf(host) + 1);
    }

    function buildSectionPrompt(target) {
      return [
        'You are an editor improving ONE section of a draft process-documentation page. Rewrite just that section so it is clearer and easier to follow.',
        '',
        'Rules:',
        '- Keep the meaning and the author\u2019s voice, and keep it short. Fix typos and unclear wording. Add detail only when the rest of the page already supports it.',
        '- Do not invent facts, numbers, names, systems or policies that are not on the page. If the rewrite would need a fact only the author knows, keep the original wording for that part.',
        '- If Visibility is Client-Safe, avoid wording that only makes sense for internal staff.',
        '- A title or description is a single plain-text line. A summary or text block may use **bold**, _italic_, lines starting with "- " for bullets and "1. " for numbers.',
        '',
        'Reply with ONLY a JSON object: {"text": "the full rewritten text", "reason": "under 120 characters, why it is better"}. For a step you may also include "title" (the rewritten step title). If nothing needs changing, reply with {}.',
        '',
        'Section to improve: ' + target,
        '',
        'The whole page, for context:',
        describePageForAi()
      ].join(NL);
    }

    async function runSectionAssist(host, button) {
      if (aiController) {
        showNotice('AI assist is already working on something. Try again in a moment.');
        return;
      }
      if (aiUnavailable) {
        showNotice('AI assist isn\u2019t available in this view.');
        return;
      }

      aiController = new AbortController();
      var controller = aiController;
      button.classList.add('is-busy');
      try {
        var sample = await getSample();
        if (!sample) {
          aiUnavailable = true;
          updateSaveState();
          showNotice('AI assist isn\u2019t available in this view.');
          return;
        }
        var target = targetNameFor(host);
        var result = await sample.json(buildSectionPrompt(target), { modelTier: 'default', signal: controller.signal });
        var item = Array.isArray(result) ? result[0] : result;
        var suggestion = item && typeof item === 'object' ? cleanSuggestion(Object.assign({}, item, { target: target, action: 'edit' })) : null;

        if (!suggestion || !host.isConnected || changesNothing(suggestion, host)) {
          showNotice('AI assist found nothing to improve in this section.');
          return;
        }
        attachSuggestion(suggestion, host);
        showNotice('AI assist has a suggestion for this section. Use + to replace the text or x to dismiss it.');
      } catch (error) {
        handleAiError(error);
      } finally {
        aiController = null;
        button.classList.remove('is-busy');
      }
    }

    function createSectionAiButton(host) {
      var button = document.createElement('button');
      button.type = 'button';
      button.className = 'section-ai';
      button.setAttribute('aria-label', 'AI assist for this section');
      button.title = 'AI assist: suggest an improvement for this section';
      button.innerHTML = SPARKLE_ICON;
      button.addEventListener('click', function () {
        if (button.getAttribute('aria-disabled') === 'true') {
          showNotice('Add some text to this section first, then AI assist can improve it.');
          return;
        }
        runSectionAssist(host, button);
      });
      return button;
    }

    // Called after every change: every section always shows the button, but it only works once the
    // section has text
    function ensureSectionAiButtons() {
      allSections().forEach(function (host) {
        var button = host.querySelector(':scope > .section-ai');
        if (!button) {
          button = createSectionAiButton(host);
          host.appendChild(button);
        }
        var hasText = isSectionFilled(host);
        button.setAttribute('aria-disabled', String(!hasText));
        button.title = hasText ? 'AI assist: suggest an improvement for this section' : 'Add some text to use AI assist on this section';
      });
    }

