    // The first step is required (red *). Every other block can be removed (red x).
    function setRequiredDecoration(block, isRequired) {
      var mark = block.querySelector('.required-mark');
      var removeButton = block.querySelector('.remove-block');
      if (isRequired) {
        if (removeButton) { removeButton.remove(); }
        if (!mark) { block.appendChild(createRequiredMark()); }
      } else {
        if (mark) { mark.remove(); }
        if (!removeButton) { block.appendChild(createRemoveButton(block)); }
      }
    }

    // Re-numbers steps and refreshes which block is required, after any add or remove
    // Steps that sit together form a step section. Numbering restarts at 1 in each section, each
    // section ends with a "+ Add step" button, and the first step on the page is the required one.
    function refreshBlocks() {
      Array.prototype.slice.call(contentEl.querySelectorAll(':scope > .step-actions')).forEach(function (row) {
        row.remove();
      });

      var stepNumber = 0;
      var sawFirstStep = false;
      var children = Array.prototype.slice.call(contentEl.children);

      children.forEach(function (child, index) {
        var isStep = child.classList.contains('step-block');
        if (!isStep && !child.classList.contains('text-block')) { return; }

        var isRequired = false;
        if (isStep) {
          var previous = children[index - 1];
          var next = children[index + 1];
          var startsSection = !(previous && previous.classList.contains('step-block'));
          var endsSection = !(next && next.classList.contains('step-block'));

          stepNumber = startsSection ? 1 : stepNumber + 1;
          isRequired = !sawFirstStep;
          sawFirstStep = true;

          child.querySelector('.step-number').textContent = String(stepNumber);
          child.querySelector('.step-title').setAttribute('data-placeholder', isRequired ? 'Step title (required)' : 'Step title');
          if (endsSection) { child.after(createStepActions()); }
        }
        setRequiredDecoration(child, isRequired);
      });

      enforceHeaderHierarchy();
      removeRedundantInserters();
      refreshOutline();
    }

    /* ---------- Header hierarchy ----------
       Headers step down one level at a time. The first header on the page is an H1, and every
       later header is at most one level deeper than the header before it: after an H1 you can use
       H1 or H2, after an H2 you can use H1, H2 or H3, and so on. */

    // The deepest header level allowed at an insertion point (beforeNode null means the end)
    function deepestAllowedHeaderLevel(beforeNode) {
      var levelAbove = 0;
      contentBlocks().forEach(function (block) {
        var isAbove = !beforeNode || (beforeNode.compareDocumentPosition(block) & Node.DOCUMENT_POSITION_PRECEDING);
        if (isAbove && block.classList.contains('header-block')) {
          levelAbove = Number(block.getAttribute('data-level')) || 2;
        }
      });
      return Math.min(levelAbove + 1, 5);
    }

    function setHeaderLevel(block, level) {
      var field = block.querySelector('[contenteditable]');
      var replacement = document.createElement('h' + level);
      Array.prototype.forEach.call(field.attributes, function (attribute) {
        replacement.setAttribute(attribute.name, attribute.value);
      });
      replacement.className = 'block-header level-' + level;
      replacement.textContent = field.textContent;
      block.replaceChild(replacement, field);
      block.setAttribute('data-level', String(level));
      block.querySelector('.block-tag').textContent = 'H' + level;
    }

    // Adding, removing or loading headers can leave one too deep; pull it up to the deepest level allowed
    function enforceHeaderHierarchy() {
      var previous = 0;
      contentBlocks().forEach(function (block) {
        if (!block.classList.contains('header-block')) { return; }
        var level = Number(block.getAttribute('data-level')) || 2;
        var allowed = Math.min(previous + 1, 5);
        if (level > allowed) {
          setHeaderLevel(block, allowed);
          level = allowed;
        }
        previous = level;
      });
    }

    // No + line sits directly above or below "+ Add a block" (the button covers that spot), and two
    // + lines never sit side by side. The + under the opening paragraph always stays.
    function removeRedundantInserters() {
      var addButton = byId('add-block');
      var topLine = contentEl.firstElementChild;
      if (addButton) {
        [addButton.previousElementSibling, addButton.nextElementSibling].forEach(function (neighbour) {
          if (neighbour && neighbour !== topLine && neighbour.classList.contains('section-insert')) { neighbour.remove(); }
        });
      }
      Array.prototype.slice.call(contentEl.querySelectorAll(':scope > .section-insert')).forEach(function (line) {
        var before = line.previousElementSibling;
        if (before && before.classList.contains('section-insert')) { line.remove(); }
      });
    }

    // Every block in page order: { type: 'paragraph' | 'header' | 'step', title?, text }
    function readBlocks() {
      return contentBlocks().map(function (block) {
        if (block.classList.contains('step-block')) {
          return {
            type: 'step',
            number: Number(block.querySelector('.step-number').textContent),
            title: readText(block.querySelector('.step-title')),
            text: readText(block.querySelector('.step-text'))
          };
        }
        var type = Object.keys(TEXT_BLOCKS).filter(function (key) {
          return block.classList.contains(TEXT_BLOCKS[key].blockClass);
        })[0] || 'paragraph';
        var result = { type: type, text: readText(block.querySelector('[contenteditable]')) };
        if (type === 'header') { result.level = Number(block.getAttribute('data-level')) || 2; }
        return result;
      });
    }

    function buildStepBlock(title, text) {
      var block = document.createElement('div');
      block.className = 'block step-block';

      var number = document.createElement('span');
      number.className = 'step-number';

      var body = document.createElement('div');

      var heading = document.createElement('h2');
      heading.className = 'step-title';
      heading.contentEditable = 'true';
      heading.spellcheck = true;
      heading.setAttribute('data-single-line', '');
      heading.setAttribute('data-placeholder', 'Step title');
      heading.textContent = title || '';

      var paragraph = document.createElement('p');
      paragraph.className = 'step-text';
      paragraph.contentEditable = 'true';
      paragraph.spellcheck = true;
      paragraph.setAttribute('data-placeholder', 'Describe this step');
      paragraph.textContent = text || '';

      body.appendChild(heading);
      body.appendChild(paragraph);
      block.appendChild(number);
      block.appendChild(body);
      return block;
    }

    function readSteps() {
      return stepBlocks().map(function (block) {
        return {
          title: readText(block.querySelector('.step-title')),
          text: readText(block.querySelector('.step-text'))
        };
      });
    }

    // Real content blocks only. The container also holds the insert lines and the "+ Add a block" button.
    function contentBlocks() {
      return Array.prototype.filter.call(contentEl.children, function (child) {
        return child.classList.contains('step-block') || child.classList.contains('text-block');
      });
    }

    // Step blocks only (paragraph and header blocks share the same container)
    function stepBlocks() {
      return Array.prototype.filter.call(contentEl.children, function (child) {
        return child.classList.contains('step-block');
      });
    }

